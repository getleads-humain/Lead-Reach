async function main() {
  console.log('🌱 Seeding Workforce Agents...\n');

  for (const agent of WORKFORCE_SEED) {
    const result = await prisma.workforceAgent.upsert({
      where: { slug: agent.slug },
      update: agent,
      create: { ...agent, isManaged: true },
    });
    console.log(`  ✅ ${agent.avatar} ${agent.name} (${result.id})`);
  }

  const count = await prisma.workforceAgent.count();
  console.log(`\n✨ ${count} workforce agents ready for duty.`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
